// (for): BUNDLED_FONTS_FINGERPRINT names the bundled faces' metrics, so a text
// size measured with them can be told stale once a font import changes them. It is the first 16
// hex digits of the SHA-256 of every bundled family's and coverage face's encoded metrics. When
// the metrics are regenerated (UPDATE_BUNDLED_METRICS=1), this test rewrites the constant too:
//   UPDATE_BUNDLED_METRICS=1 pnpm vitest run --project @canvas/text fonts-fingerprint
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { SIZED_COVERAGE, SIZED_FAMILIES } from '../__fixtures__/sized-metrics.js';
import { LINE_BREAKING_VERSION } from '../line-break/line-break-version.js';
import {
  FALLBACK_RULES,
  fallbackFamiliesOf,
  SCRIPT_FALLBACKS,
} from '../script/fallback-families.js';
import { SHAPER_VERSION } from '../shaping/shaper.js';

import { BUNDLED_FONTS_FINGERPRINT } from './fonts-fingerprint.js';

/**
 * The fingerprint of the bundled metrics as generated now.
 *
 * @returns 16 hex digits.
 */
function currentFingerprint(): string {
  // The shaper too: a size shaped by another HarfBuzz may differ; and the line
  // breaking rules: a size wrapped by other rules may differ; and the script fallback
  // table: a size set in another script face may differ.
  // Not the decoration metrics: an underline moves no glyph, so no stored size goes
  // stale when they change.
  const data = JSON.stringify({
    families: SIZED_FAMILIES,
    coverage: SIZED_COVERAGE,
    shaper: SHAPER_VERSION,
    lineBreaking: LINE_BREAKING_VERSION,
    scriptFallbacks: SCRIPT_FALLBACKS.map(([script]) => [script, fallbackFamiliesOf(script)]),
    fallbackRules: FALLBACK_RULES,
  });
  return createHash('sha256').update(data).digest('hex').slice(0, 16);
}

if (process.env.UPDATE_BUNDLED_METRICS === '1') {
  writeFileSync(
    new URL('./fonts-fingerprint.ts', import.meta.url),
    [
      '// Generated by src/bundled/fonts-fingerprint.test.ts; do not edit.',
      '',
      '/**',
      ' * Names the bundled faces’ metrics and the shaper: it changes whenever',
      ' * a font import changes the bundled or coverage faces, the shaper, the line breaking or the',
      ' * script fallback table change, so a text',
      ' * size measured with them (and stored with this fingerprint) can be told stale and',
      ' * measured again. 16 hex digits.',
      ' */',
      `export const BUNDLED_FONTS_FINGERPRINT = '${currentFingerprint()}';`,
      '',
    ].join('\n'),
  );
}

describe('SHAPER_VERSION', () => {
  it('names the installed harfbuzzjs', () => {
    const manifest = JSON.parse(
      readFileSync(new URL('../../node_modules/harfbuzzjs/package.json', import.meta.url), 'utf8'),
    ) as { readonly version: string };
    expect(SHAPER_VERSION).toBe(`harfbuzzjs@${manifest.version}`);
  });
});

describe('BUNDLED_FONTS_FINGERPRINT', () => {
  it('names the bundled metrics as generated, so regenerating them changes it', () => {
    expect(BUNDLED_FONTS_FINGERPRINT).toMatch(/^[0-9a-f]{16}$/);
    expect(BUNDLED_FONTS_FINGERPRINT).toBe(currentFingerprint());
  });
});
