/// <reference types="node" />
// The file of each face in the Noto coverage catalogue
// (packages/app/assets/fonts/script-coverage/catalogue.json), by path from the repository root,
// so a server can measure script text with the faces the app draws it with. Fails when the
// catalogue changes and the table was not regenerated:
//
//   UPDATE_BUNDLED_METRICS=1 pnpm vitest run --project @canvas/text coverage-font-files
//   pnpm exec prettier --write packages/text/src/bundled/coverage-font-files.ts
// (The table holds paths under the coverage folder; COVERAGE_FONT_FILES adds the folder.)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { SCRIPT_COVERAGE_FAMILIES } from '../symbols/script-coverage.js';

import {
  COVERAGE_FONT_FILES,
  coverageFontFile,
  serverCoverageFamilies,
  serverCoverageFontFilePaths,
} from './coverage-font-file.js';

const REPO_ROOT = new URL('../../../../', import.meta.url);
const COVERAGE = 'packages/app/assets/fonts/script-coverage/';

interface Catalogue {
  readonly entries: readonly {
    readonly family: string;
    readonly faces: readonly { weight: 400 | 700; isItalic: boolean; url: string }[];
  }[];
}

/**
 * Every face in the coverage catalogue, in catalogue order.
 *
 * @returns Each face's family, weight, slant and path.
 */
function faceFiles(): (readonly [string, 400 | 700, boolean, string])[] {
  const catalogue = JSON.parse(
    readFileSync(new URL(`${COVERAGE}catalogue.json`, REPO_ROOT), 'utf8'),
  ) as Catalogue;
  return catalogue.entries.flatMap(({ family, faces }) =>
    faces.map(
      ({ weight, isItalic, url }) => [family, weight, isItalic, `${COVERAGE}${url}`] as const,
    ),
  );
}

if (process.env.UPDATE_BUNDLED_METRICS === '1') {
  const rows = faceFiles().map(
    ([family, weight, isItalic, path]) =>
      `  [${JSON.stringify(family)}, ${String(weight)}, ${String(isItalic)}, ${JSON.stringify(path.slice(COVERAGE.length))}],`,
  );
  writeFileSync(
    new URL('./coverage-font-files.ts', import.meta.url),
    [
      '// Generated by src/bundled/coverage-font-files.test.ts; do not edit.',
      "import type { FontWeight } from '@canvas/schema';",
      '',
      '/**',
      ' * The file of each Noto coverage face: family, weight, italic, and the path under',
      ' * the coverage folder (`COVERAGE_FONT_FOLDER`).',
      ' */',
      'export const COVERAGE_FACE_FILES: readonly (readonly [',
      '  family: string,',
      '  weight: FontWeight,',
      '  isItalic: boolean,',
      '  file: string,',
      '])[] = [',
      ...rows,
      '];',
      '',
    ].join('\n'),
  );
}

describe('coverage font files', () => {
  it('lists every face of the coverage catalogue, each with its file on disk', () => {
    expect(COVERAGE_FONT_FILES).toEqual(faceFiles());
    for (const [, , , path] of COVERAGE_FONT_FILES) {
      expect(existsSync(new URL(path, REPO_ROOT)), path).toBe(true);
    }
  });

  it('names the file of a coverage face, and none for another face', () => {
    expect(coverageFontFile({ family: 'Noto Sans Thai', weight: 700, isItalic: false })).toBe(
      `${COVERAGE}notosansthai/700.ttf`,
    );
    expect(coverageFontFile({ family: 'Inter', weight: 400, isItalic: false })).toBeUndefined();
  });

  it('deploys every script face to servers but the five Han faces', () => {
    const han = ['Noto Sans SC', 'Noto Sans TC', 'Noto Sans HK', 'Noto Sans JP', 'Noto Sans KR'];
    expect(serverCoverageFamilies()).toEqual(
      SCRIPT_COVERAGE_FAMILIES.filter((family) => !han.includes(family)),
    );
    const paths = serverCoverageFontFilePaths();
    expect(new Set(paths).size).toBe(paths.length);
    expect(paths).toContain(`${COVERAGE}notosansarabic/400.ttf`);
    expect(paths.some((path) => path.includes('notosanssc/'))).toBe(false);
  });
});
