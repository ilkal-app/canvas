// The shader build behind compile-shaders.ts: WGSL → GLSL ES 3.0 with naga (compiled to
// WebAssembly, so no Rust toolchain is needed). For every `<name>.wgsl` in a directory it
// produces, next to the source:
//   <name>.vert.glsl, <name>.frag.glsl   the generated stages, committed for review
//   <name>.generated.ts                  a GpuShaderSource embedding the WGSL and both stages
// WGSL is the single source.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

import { nagaVersion, translate } from 'naga-wasm';

import { clipShaderSource, isClippedShader } from './clip-shader.ts';
import { gammaShaderSource } from './coverage-gamma-shader.ts';
import { gradientShaderSource, gradientVariantName } from './gradient-shader.ts';
import { imageFillShaderSource, imageFillVariantName } from './image-fill-shader.ts';
import { moveShaderSource } from './move-shader.ts';
import {
  TEXT_PAGE_VARIANT_SLOTS,
  textPageVariantName,
  textPageVariantSource,
} from './text-page-shader.ts';

/** Every shader names its entry points the same way, so the GLSL stages can be found. */
const VERTEX_ENTRY_POINT = 'vertexMain';
const FRAGMENT_ENTRY_POINT = 'fragmentMain';

/** One generated file: its name beside the `.wgsl` source and its full content. */
export interface ShaderOutput {
  readonly fileName: string;
  readonly content: string;
}

/** What a build of a shader directory found. */
export interface ShaderBuildResult {
  /** The number of `.wgsl` sources. */
  readonly shaderCount: number;
  /** Outputs that were missing or differed from what the sources generate, in order. */
  readonly staleFiles: readonly string[];
}

function toGlsl(wgsl: string, stage: 'vertex' | 'fragment', entryPoint: string): string {
  return translate({
    from: 'wgsl',
    to: 'glsl',
    source: wgsl,
    options: {
      version: '300 es',
      stage,
      entryPoint,
      // naga's default flips y and remaps depth for wgpu's own GL presentation path. The
      // WebGL2 backend draws straight to the canvas, where clip space already matches WebGPU's.
      flags: { adjustCoordinateSpace: false },
    },
  });
}

function toConstantName(shaderName: string): string {
  return `${shaderName.replaceAll('-', '_').toUpperCase()}_SHADER`;
}

/** The solid sources of the generated gradient variants, by variant name. */
const GRADIENT_SOURCES: Readonly<Record<string, string>> = Object.fromEntries(
  ['sdf-shape', 'path', 'solid-rect'].map((name) => [gradientVariantName(name) ?? name, name]),
);

/** The solid sources of the generated image-fill variants, by variant name. */
const IMAGE_FILL_SOURCES: Readonly<Record<string, string>> = Object.fromEntries(
  ['sdf-shape'].map((name) => [imageFillVariantName(name) ?? name, name]),
);

/**
 * Where a generated shader comes from, for its header: its own `.wgsl`, or a solid source with
 * the scripts that derive a variant from it.
 *
 * @param shaderName - The generated shader's name.
 * @returns The source note.
 */
function sourceOf(shaderName: string): string {
  const textPages = /^(.*)-pages-\d+$/.exec(shaderName)?.[1];
  if (textPages !== undefined)
    return `${textPages}.wgsl and clip-shader.ts and text-page-shader.ts`;
  const isMove = shaderName.endsWith('-move');
  const base = shaderName.replace(/-move$/, '');
  const gradientSolid = GRADIENT_SOURCES[base];
  const imageSolid = IMAGE_FILL_SOURCES[base];
  const solid = gradientSolid ?? imageSolid;
  const scripts = [
    ...(isClippedShader(solid ?? base) ? ['clip-shader.ts'] : []),
    ...(gradientSolid === undefined ? [] : ['gradient-shader.ts']),
    ...(imageSolid === undefined ? [] : ['image-fill-shader.ts']),
    ...(isMove ? ['move-shader.ts'] : []),
  ];
  return `${solid ?? base}.wgsl${scripts.length === 0 ? '' : ` and ${scripts.join(' and ')}`}`;
}

function generatedModule(
  shaderName: string,
  wgsl: string,
  vertex: string,
  fragment: string,
): string {
  return `// Generated by packages/engine/scripts/compile-shaders.ts from ${sourceOf(shaderName)} with naga ${nagaVersion}.
// Do not edit: change the .wgsl file and run \`pnpm --filter @canvas/engine shaders\`.
import type { GpuShaderSource } from '../gpu-shader.js';

/** The ${shaderName} pass's shaders: the WGSL source and its naga-generated GLSL ES 3.0 stages. */
export const ${toConstantName(shaderName)}: GpuShaderSource = {
  label: ${JSON.stringify(shaderName)},
  wgsl: ${JSON.stringify(wgsl)},
  vertexEntryPoint: ${JSON.stringify(VERTEX_ENTRY_POINT)},
  fragmentEntryPoint: ${JSON.stringify(FRAGMENT_ENTRY_POINT)},
  glslVertex: ${JSON.stringify(vertex)},
  glslFragment: ${JSON.stringify(fragment)},
};
`;
}

function glslFile(shaderName: string, glsl: string): string {
  const header = `// Generated from ${sourceOf(shaderName)} by packages/engine/scripts/compile-shaders.ts with naga ${nagaVersion}. Do not edit.\n`;
  return header + glsl;
}

/**
 * Generates one shader's outputs in memory.
 *
 * @param shaderName - The source's file name without `.wgsl`.
 * @param wgsl - The WGSL source.
 * @returns The vertex stage, the fragment stage and the generated module, in that order.
 * @throws {Error} When naga cannot parse, validate or translate the source (a `NagaError`).
 */
export function shaderOutputs(shaderName: string, wgsl: string): ShaderOutput[] {
  const vertex = toGlsl(wgsl, 'vertex', VERTEX_ENTRY_POINT);
  const fragment = toGlsl(wgsl, 'fragment', FRAGMENT_ENTRY_POINT);
  return [
    { fileName: `${shaderName}.vert.glsl`, content: glslFile(shaderName, vertex) },
    { fileName: `${shaderName}.frag.glsl`, content: glslFile(shaderName, fragment) },
    {
      fileName: `${shaderName}.generated.ts`,
      content: generatedModule(shaderName, wgsl, vertex, fragment),
    },
  ];
}

function readIfPresent(path: string): string | undefined {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return undefined;
  }
}

/**
 * Builds every `.wgsl` shader in a directory. `write` mode rewrites every output; `check` mode
 * writes nothing and lists the outputs that are missing or differ from what the sources
 * generate, so a stale commit fails the gate.
 *
 * @param directory - The directory holding the `.wgsl` sources and their outputs.
 * @param mode - Whether to write the outputs or only compare them.
 * @returns The number of sources and, in `check` mode, the stale outputs.
 */
export function buildShaderDirectory(
  directory: string,
  mode: 'write' | 'check',
): ShaderBuildResult {
  const sources = readdirSync(directory)
    .filter((fileName) => fileName.endsWith('.wgsl'))
    .sort();
  const staleFiles: string[] = [];
  for (const source of sources) {
    const name = basename(source, '.wgsl');
    const wgsl = gammaShaderSource(
      name,
      clipShaderSource(name, readFileSync(join(directory, source), 'utf8')),
    );
    const move = moveShaderSource(name, wgsl);
    const outputs = shaderOutputs(name, wgsl);
    if (move !== undefined) outputs.push(...shaderOutputs(`${name}-move`, move));
    const gradient = gradientShaderSource(name, wgsl);
    const gradientName = gradientVariantName(name);
    if (gradient !== undefined && gradientName !== undefined) {
      outputs.push(...shaderOutputs(gradientName, gradient));
      const gradientMove = moveShaderSource(gradientName, gradient);
      if (gradientMove !== undefined)
        outputs.push(...shaderOutputs(`${gradientName}-move`, gradientMove));
    }
    for (const slots of TEXT_PAGE_VARIANT_SLOTS) {
      const variant = textPageVariantSource(name, wgsl, slots);
      const variantName = textPageVariantName(name, slots);
      if (variant !== undefined && variantName !== undefined) {
        outputs.push(...shaderOutputs(variantName, variant));
      }
    }
    const imageFill = imageFillShaderSource(name, wgsl);
    const imageFillName = imageFillVariantName(name);
    if (imageFill !== undefined && imageFillName !== undefined) {
      outputs.push(...shaderOutputs(imageFillName, imageFill));
      const imageFillMove = moveShaderSource(imageFillName, imageFill);
      if (imageFillMove !== undefined)
        outputs.push(...shaderOutputs(`${imageFillName}-move`, imageFillMove));
    }
    for (const { fileName, content } of outputs) {
      const path = join(directory, fileName);
      if (mode === 'write') {
        writeFileSync(path, content);
      } else if (readIfPresent(path) !== content) {
        staleFiles.push(fileName);
      }
    }
  }
  return { shaderCount: sources.length, staleFiles };
}
