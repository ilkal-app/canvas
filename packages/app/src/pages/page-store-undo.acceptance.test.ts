// Split commands through the app's page stores are one undo step.
import { describe, expect, it } from 'vitest';

import {
  createHistory,
  createLargeBoardObjects,
  createObjectsCommand,
  deleteObjectsCommand,
  runCommand,
  YjsDocumentStore,
  type CommandEnvironment,
  type DocumentStore,
  type NewObject,
} from '@canvas/document';
import { createSeededIdGenerator, type PrincipalId } from '@canvas/schema';

import { createPageView } from './create-page-view.js';
import { PageBoardStore } from './page-board-store.js';

/** Fields stamped by createObjects rather than supplied by a listed object. */
const GENERATED = new Set(['z', 'createdBy', 'createdAt', 'updatedAt']);
const ORIGIN = { kind: 'user', principalId: 'user:ada' as PrincipalId } as const;

/**
 * Lists the deterministic large-board mix for createObjects.
 *
 * @param count - Number of objects.
 * @returns The objects without fields generated by the command.
 */
function listed(count: number): NewObject[] {
  return createLargeBoardObjects(count, 557).map(
    (object) =>
      Object.fromEntries(
        Object.entries(object).filter(([key]) => !GENERATED.has(key)),
      ) as unknown as NewObject,
  );
}

/**
 * Gives each command a deterministic clock and id sequence.
 *
 * @param seed - The id sequence seed.
 * @returns A command environment.
 */
function environment(seed: number): CommandEnvironment {
  return { clock: () => 1_770_000_000_000, createId: createSeededIdGenerator(seed) };
}

/**
 * Runs createObjects and requires it to apply.
 *
 * @param store - The store to write through.
 * @param count - Number of objects.
 * @param seed - The generated id sequence seed.
 * @returns The created object ids.
 * @throws {Error} When the command is rejected.
 */
function create(store: DocumentStore, count: number, seed: number) {
  const outcome = runCommand(
    store,
    ORIGIN,
    createObjectsCommand,
    { objects: listed(count) },
    environment(seed),
  );
  if (outcome.status === 'rejected') {
    throw new Error(`createObjects was rejected: ${JSON.stringify(outcome.errors)}`);
  }
  return outcome.result.ids;
}

describe('page stores forward split undo steps', { timeout: 30_000 }, () => {
  it('undoes and redoes all 2,500 objects created through PageBoardStore', () => {
    const store = new YjsDocumentStore();
    const page = store.read().pages.keys().next().value;
    if (page === undefined) throw new Error('the default page exists');
    const writer = new PageBoardStore(store, () => page);
    const history = createHistory(store, ORIGIN.principalId, { captureTimeout: 0 });

    expect(create(writer, 2_500, 1)).toHaveLength(2_500);
    expect(store.read().objects.size).toBe(2_500);
    expect(history.undo()).toBe(true);
    expect(store.read().objects.size).toBe(0);
    expect(history.canUndo()).toBe(false);
    expect(history.redo()).toBe(true);
    expect(store.read().objects.size).toBe(2_500);
    history.destroy();
    writer.destroy();
    store.destroy();
  });

  it('undoes and redoes all 2,500 objects deleted through PageBoardStore', () => {
    const store = new YjsDocumentStore();
    const ids = create(store, 2_500, 1);
    const page = store.read().pages.keys().next().value;
    if (page === undefined) throw new Error('the default page exists');
    const writer = new PageBoardStore(store, () => page);
    const history = createHistory(store, ORIGIN.principalId, { captureTimeout: 0 });

    const outcome = runCommand(
      writer,
      ORIGIN,
      deleteObjectsCommand,
      { ids: [...ids] },
      environment(2),
    );
    if (outcome.status === 'rejected') {
      throw new Error(`deleteObjects was rejected: ${JSON.stringify(outcome.errors)}`);
    }
    expect(outcome.result.deletedIds).toHaveLength(2_500);
    expect(store.read().objects.size).toBe(0);
    expect(history.undo()).toBe(true);
    expect(store.read().objects.size).toBe(2_500);
    expect(history.canUndo()).toBe(false);
    expect(history.redo()).toBe(true);
    expect(store.read().objects.size).toBe(0);
    history.destroy();
    writer.destroy();
    store.destroy();
  });

  it('undoes and redoes all 2,500 objects created through PageScopedStore', () => {
    const store = new YjsDocumentStore();
    const { view, release } = createPageView(store, ORIGIN, environment(1), {});
    const history = createHistory(store, ORIGIN.principalId, { captureTimeout: 0 });

    expect(create(view, 2_500, 2)).toHaveLength(2_500);
    expect(view.read().objects.size).toBe(2_500);
    expect(history.undo()).toBe(true);
    expect(store.read().objects.size).toBe(0);
    expect(view.read().objects.size).toBe(0);
    expect(history.canUndo()).toBe(false);
    expect(history.redo()).toBe(true);
    expect(view.read().objects.size).toBe(2_500);
    history.destroy();
    release();
    store.destroy();
  });
});
