/// <reference types="node" />
// The generated tables under coverage-generated/ against the symbol faces they were made from
// (Noto Sans Math and Noto Sans Symbols 2, in packages/app/assets/fonts/script-coverage),
// decoded to exactly the metrics the app's font library builds from the files. They are kept apart
// from the bundled families: text can fall back to them, never name them. Fails when a font or the
// catalogue changes and the tables were not regenerated:
//
//   UPDATE_BUNDLED_METRICS=1 pnpm vitest run --project @canvas/text coverage-font-metrics bundled-font-files expanding-codepoints
//   pnpm exec prettier --write packages/text/src/bundled/coverage-generated packages/text/src/bundled/font-files.ts packages/text/src/bundled/expanding-glyphs.ts
import { readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import type { FontFaceKey } from '../font/font-face.js';
import { createFontMetrics } from '../font/font-metrics.js';
import { parseFont } from '../font/parse-font.js';
import { SYMBOL_COVERAGE_FAMILIES } from '../symbols/symbol-coverage.js';

import { symbolCoverageMetrics } from './coverage-fonts.js';
import { encodeFaceMetrics } from './face-encoding.js';

const COVERAGE = new URL('../../../app/assets/fonts/script-coverage/', import.meta.url);
const GENERATED = new URL('./coverage-generated/', import.meta.url);

interface FaceFile {
  readonly face: FontFaceKey;
  readonly file: URL;
}

interface Catalogue {
  readonly entries: readonly {
    readonly family: string;
    readonly faces: readonly {
      weight: 400 | 700;
      isItalic: boolean;
      url: string;
      /** The file a measuring server shapes with, when not `url`. */
      metricsUrl?: string;
    }[];
  }[];
}

/**
 * The symbol faces, in fallback order.
 *
 * @returns The faces and their files.
 */
function symbolFaceFiles(): FaceFile[] {
  const catalogue = JSON.parse(
    readFileSync(new URL('catalogue.json', COVERAGE), 'utf8'),
  ) as Catalogue;
  return SYMBOL_COVERAGE_FAMILIES.flatMap((family) => {
    const entry = catalogue.entries.find((candidate) => candidate.family === family);
    if (entry === undefined) throw new Error(`${family} is not in the coverage catalogue`);
    return entry.faces.map(({ weight, isItalic, url, metricsUrl }) => ({
      face: { family, weight, isItalic },
      file: new URL(metricsUrl ?? url, COVERAGE),
    }));
  });
}

/**
 * A face's metrics and encoded table, from its file.
 *
 * @param faceFile - The face and its file.
 * @returns Both.
 */
function measuredFace(faceFile: FaceFile): {
  metrics: ReturnType<typeof createFontMetrics>;
  encoded: string;
} {
  const bytes = readFileSync(faceFile.file);
  const font = parseFont(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.length));
  const metrics = createFontMetrics(faceFile.face, font);
  return { metrics, encoded: encodeFaceMetrics(metrics, font.unitsPerEm) };
}

/**
 * Writes coverage-generated/index.ts from the font files (`UPDATE_BUNDLED_METRICS=1`).
 *
 * @param faces - The symbol faces.
 */
function writeGenerated(faces: readonly FaceFile[]): void {
  for (const name of readdirSync(GENERATED)) rmSync(new URL(name, GENERATED));
  const entries = faces.map((faceFile) => {
    const { family, weight, isItalic } = faceFile.face;
    const { encoded } = measuredFace(faceFile);
    return (
      `  { family: ${JSON.stringify(family).replace(/"/g, "'")}, weight: ${String(weight)}, ` +
      `isItalic: ${String(isItalic)}, metrics: '${encoded}' },`
    );
  });
  writeFileSync(
    new URL('index.ts', GENERATED),
    '// Generated by src/bundled/coverage-font-metrics.test.ts; do not edit.\n' +
      "import type { EncodedCoverageFace } from '../coverage-fonts.js';\n\n" +
      "/** The symbol faces' encoded metrics, in fallback order. */\n" +
      `export const COVERAGE_FACES: readonly EncodedCoverageFace[] = [\n${entries.join('\n')}\n];\n`,
  );
}

const faces = symbolFaceFiles();
if (process.env.UPDATE_BUNDLED_METRICS === '1') writeGenerated(faces);

describe('the symbol coverage metrics tables', () => {
  it('decode to exactly the metrics of the symbol faces, in fallback order', () => {
    expect(symbolCoverageMetrics()).toEqual(
      faces.map((faceFile) => measuredFace(faceFile).metrics),
    );
  });
});
