// Acceptance
import { describe, expect, it } from 'vitest';

import { resolveInstance, type BoardObject, type InstanceObject } from '@canvas/schema';

import { YjsDocumentStore } from '../store/yjs-document-store.js';

import { applyCommand, mustGet, testEnvironment } from './__fixtures__/command-fixtures.js';
import {
  placeInstance,
  seedLeafMain,
  seedMainWithChildren,
} from './__fixtures__/component-boards.js';
import {
  AGENT_FOR_ADA,
  codesOf,
  expectRefusedBy,
  fieldOf,
  mustFindCommand,
} from './__fixtures__/component-fixtures.js';

/**
 * Copyable object data, omitting metadata regenerated by createObjects.
 *
 * @param object - The source object.
 * @returns Input fields for createObjects.
 */
function copyInput(object: BoardObject): Record<string, unknown> {
  return Object.fromEntries(
    Object.entries(object).filter(
      ([key]) => !['z', 'createdBy', 'createdAt', 'updatedAt'].includes(key),
    ),
  );
}

describe('variants across detach, agents and copy', () => {
  it('materialises composed presets under own records so detached children match the resolved view', () => {
    const store = new YjsDocumentStore();
    const { mainId, noteId, boxId } = seedMainWithChildren(store);
    applyCommand(store, mustFindCommand('setVariantAxes'), {
      componentId: mainId,
      axes: [
        { name: 'state', values: ['rest', 'hover'] },
        { name: 'tone', values: ['plain', 'warm'] },
      ],
    });
    applyCommand(store, mustFindCommand('setVariantPreset'), {
      componentId: mainId,
      axis: 'state',
      value: 'hover',
      path: noteId,
      override: { text: 'Hover', color: [1, 0, 0, 1] },
    });
    applyCommand(store, mustFindCommand('setVariantPreset'), {
      componentId: mainId,
      axis: 'tone',
      value: 'warm',
      path: boxId,
      override: { fill: [0, 1, 0, 1] },
    });
    const id = placeInstance(store, mainId, {
      instanceId: 'copy',
      variant: { state: 'hover', tone: 'warm' },
      overrides: { [noteId]: { color: [0, 0, 1, 1] } },
    });
    const resolved = resolveInstance(store.read(), mustGet(store, id) as InstanceObject).objects;
    const { result } = applyCommand(store, mustFindCommand('detachInstance'), { id });
    const idMap = (result as { idMap: Record<string, string> }).idMap;
    expect(mustGet(store, id).type).toBe('frame');
    for (const source of resolved) {
      const path = source.id.slice(`${id}/`.length);
      const stored = mustGet(store, idMap[path] ?? 'missing');
      const appearance = (object: BoardObject) =>
        Object.fromEntries(
          Object.entries(object).filter(
            ([key]) =>
              !['id', 'parentId', 'pageId', 'z', 'createdBy', 'createdAt', 'updatedAt'].includes(
                key,
              ),
          ),
        );
      expect(appearance(stored)).toEqual(appearance(source));
    }
  });

  it('keeps a nested instance selection when its outer instance is detached', () => {
    const store = new YjsDocumentStore();
    seedLeafMain(store, 'inner', { x: 0, y: 0 });
    applyCommand(store, mustFindCommand('setVariantAxes'), {
      componentId: 'inner',
      axes: [{ name: 'state', values: ['rest', 'hover'] }],
    });
    seedLeafMain(store, 'outer', { x: 1000, y: 0 });
    placeInstance(store, 'inner', {
      instanceId: 'nested',
      parentId: 'outer',
      x: 1050,
      y: 0,
      variant: { state: 'hover' },
    });
    const outer = placeInstance(store, 'outer', { instanceId: 'outer-copy', x: 2000, y: 0 });
    const { result } = applyCommand(store, mustFindCommand('detachInstance'), { id: outer });
    const nestedId = (result as { idMap: Record<string, string> }).idMap.nested;
    expect(mustGet(store, nestedId ?? 'missing')).toMatchObject({
      type: 'instance',
      variant: { state: 'hover' },
    });
  });

  it('refuses an agent editing another person’s axes or presets and allows edits on its own main', () => {
    const store = new YjsDocumentStore();
    const { mainId, noteId } = seedMainWithChildren(store);
    const axes = mustFindCommand('setVariantAxes');
    expect(
      codesOf(
        expectRefusedBy(store, AGENT_FOR_ADA, axes, {
          componentId: mainId,
          axes: [{ name: 'state', values: ['rest', 'hover'] }],
        }),
      ),
    ).toEqual(['not-own-main']);
    applyCommand(store, axes, {
      componentId: mainId,
      axes: [{ name: 'state', values: ['rest', 'hover'] }],
    });
    const preset = {
      componentId: mainId,
      axis: 'state',
      value: 'hover',
      path: noteId,
      override: { text: 'Hover' },
    };
    expect(
      codesOf(expectRefusedBy(store, AGENT_FOR_ADA, mustFindCommand('setVariantPreset'), preset)),
    ).toEqual(['not-own-main']);
    applyCommand(store, mustFindCommand('setVariantPreset'), preset);
    expect(
      codesOf(
        expectRefusedBy(store, AGENT_FOR_ADA, mustFindCommand('resetVariantPreset'), {
          componentId: mainId,
          axis: 'state',
          value: 'hover',
        }),
      ),
    ).toEqual(['not-own-main']);
    seedLeafMain(store, 'agent-main', { x: 2000, y: 0 }, AGENT_FOR_ADA);
    applyCommand(
      store,
      axes,
      { componentId: 'agent-main', axes: [{ name: 'state', values: ['rest', 'hover'] }] },
      AGENT_FOR_ADA,
      testEnvironment(41),
    );
    applyCommand(
      store,
      mustFindCommand('setVariantPreset'),
      {
        componentId: 'agent-main',
        axis: 'state',
        value: 'hover',
        path: 'agent-main-leaf',
        override: { text: 'Own' },
      },
      AGENT_FOR_ADA,
      testEnvironment(41),
    );
    applyCommand(
      store,
      mustFindCommand('resetVariantPreset'),
      { componentId: 'agent-main', axis: 'state', value: 'hover' },
      AGENT_FOR_ADA,
      testEnvironment(41),
    );
    expect(fieldOf(store, 'agent-main', 'variantAxes')).toEqual([
      { name: 'state', values: ['rest', 'hover'] },
    ]);
  });

  it('lets an agent switch an instance it may edit even when the main belongs to someone else', () => {
    const store = new YjsDocumentStore();
    const { mainId } = seedMainWithChildren(store);
    applyCommand(store, mustFindCommand('setVariantAxes'), {
      componentId: mainId,
      axes: [{ name: 'state', values: ['rest', 'hover'] }],
    });
    const id = placeInstance(
      store,
      mainId,
      { instanceId: 'agent-copy' },
      AGENT_FOR_ADA,
      testEnvironment(41),
    );
    applyCommand(
      store,
      mustFindCommand('setInstanceVariant'),
      { id, variant: { state: 'hover' } },
      AGENT_FOR_ADA,
      testEnvironment(41),
    );
    expect(fieldOf(store, id, 'variant')).toEqual({ state: 'hover' });
  });

  it('copies a main with its presets and an instance with its selection through createObjects', () => {
    const store = new YjsDocumentStore();
    const { mainId, noteId } = seedMainWithChildren(store);
    applyCommand(store, mustFindCommand('setVariantAxes'), {
      componentId: mainId,
      axes: [{ name: 'state', values: ['rest', 'hover'] }],
    });
    applyCommand(store, mustFindCommand('setVariantPreset'), {
      componentId: mainId,
      axis: 'state',
      value: 'hover',
      path: noteId,
      override: { text: 'Hover' },
    });
    const id = placeInstance(store, mainId, { instanceId: 'chosen', variant: { state: 'hover' } });
    const objects = [mainId, noteId, id].map((key) => copyInput(mustGet(store, key)));
    const { changes } = applyCommand(store, mustFindCommand('createObjects'), { objects });
    const copied = changes.created.map((key) => mustGet(store, key));
    const main = copied.find((object) => object.type === 'component');
    const note = copied.find((object) => object.type === 'sticky');
    const instance = copied.find((object) => object.type === 'instance');
    expect(main).toMatchObject({
      variantAxes: [{ name: 'state', values: ['rest', 'hover'] }],
      variantPresets: {
        'state=rest': {},
        'state=hover': { [note?.id ?? 'missing']: { text: 'Hover' } },
      },
    });
    expect(instance).toMatchObject({ mainId: main?.id, variant: { state: 'hover' } });
    const { changes: duplicateChanges } = applyCommand(
      store,
      mustFindCommand('createObjects'),
      { objects: [copyInput(mustGet(store, id))] },
      undefined,
      testEnvironment(43),
    );
    expect(mustGet(store, duplicateChanges.created[0] ?? 'missing')).toMatchObject({
      mainId,
      variant: { state: 'hover' },
    });
  });
});
