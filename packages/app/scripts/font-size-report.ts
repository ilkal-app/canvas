// The download a text in each script costs: for each script a Noto face is chosen
// for, the bytes the app fetches for the first regular text in it — the script face, or for the
// CJK faces their base slice and their common slice(s) — and the face's regular whole. The CJK
// slices are build output (scripts/build-cjk-slices.ts), so this reads them after it has run.
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { fallbackFamiliesOf, HAN_LANGUAGE_FAMILIES, SCRIPT_CODES } from '@canvas/text';

/** The coverage faces' folder. */
const COVERAGE = fileURLToPath(new URL('../assets/fonts/script-coverage/', import.meta.url));

/** The CJK slices' folder. */
const SLICES = fileURLToPath(new URL('../assets/fonts/cjk/', import.meta.url));

/**
 * The slices a first text in a script needs from a CJK face, besides `base` (which holds the
 * kana and Bopomofo): Han's common slice, or the Korean face's common syllables.
 *
 * @param script - The script.
 * @returns The slice ids.
 */
function commonSlices(script: string): readonly string[] {
  if (script === 'Hani') return ['han-0'];
  if (script === 'Hang') return ['hangul-0', 'hangul-1'];
  return [];
}

/**
 * Bytes as a short size.
 *
 * @param bytes - The size.
 * @returns It in KB or MB.
 */
function sizeOf(bytes: number): string {
  return bytes >= 1024 * 1024
    ? `${(bytes / (1024 * 1024)).toFixed(2)} MB`
    : `${String(Math.round(bytes / 1024))} KB`;
}

/**
 * Each face's regular file, by family, from the coverage catalogue.
 *
 * @returns The files' paths under the coverage folder.
 */
function regularFiles(): ReadonlyMap<string, string> {
  const catalogue = JSON.parse(readFileSync(join(COVERAGE, 'catalogue.json'), 'utf8')) as {
    entries: { family: string; faces: { weight: number; isItalic: boolean; url: string }[] }[];
  };
  return new Map(
    catalogue.entries.flatMap(({ family, faces }) =>
      faces
        .filter(({ weight, isItalic }) => weight === 400 && !isItalic)
        .map(({ url }) => [family, url] as const),
    ),
  );
}

/**
 * The bytes a first regular text costs in a family, and its regular whole.
 *
 * @param family - The family.
 * @param script - The script the text is in.
 * @param files - Each family's regular file.
 * @returns Both, in bytes.
 */
function costOf(
  family: string,
  script: string,
  files: ReadonlyMap<string, string>,
): [first: number, whole: number] {
  const url = files.get(family) ?? '';
  const whole = statSync(join(COVERAGE, url)).size;
  if (!HAN_LANGUAGE_FAMILIES.includes(family)) return [whole, whole];
  const folder = join(SLICES, url.slice(0, url.indexOf('/')).replace(/^notosans/u, ''));
  const slice = (id: string): number => statSync(join(folder, `400-${id}.ttf`)).size;
  const first = ['base', ...commonSlices(script)].reduce((sum, id) => sum + slice(id), 0);
  const sliced = readdirSync(folder)
    .filter((name) => name.startsWith('400-'))
    .reduce((sum, name) => sum + statSync(join(folder, name)).size, 0);
  return [first, sliced];
}

/**
 * The report: one row per script a face is chosen for (Han once per language), as Markdown.
 *
 * @returns The report.
 */
export function fontSizeReport(): string {
  const files = regularFiles();
  const rows = SCRIPT_CODES.flatMap((script) => {
    const families =
      script === 'Hani'
        ? HAN_LANGUAGE_FAMILIES
        : fallbackFamiliesOf(script)
            .filter((family) => files.has(family))
            .slice(0, 1);
    return families.map((family) => {
      const [first, whole] = costOf(family, script, files);
      return [script, family, sizeOf(first), sizeOf(whole)];
    });
  });
  return [
    '# Script font downloads',
    '',
    'Generated by `packages/app/scripts/report-font-sizes.ts`; do not edit. What the app fetches for',
    'the first regular text in each script: the script face, or for the CJK faces the base slice and',
    'the common slice(s) (S3), against the regular face whole (for CJK, all its regular slices).',
    '',
    ...table(['Script', 'Face', 'First text', 'Whole (regular)'], rows),
    '',
  ].join('\n');
}

/**
 * A Markdown table, its columns padded as Prettier pads them.
 *
 * @param header - The column titles.
 * @param rows - The cells.
 * @returns The table's lines.
 */
function table(header: readonly string[], rows: readonly (readonly string[])[]): string[] {
  const widths = header.map((title, column) =>
    Math.max(title.length, ...rows.map((row) => (row[column] ?? '').length)),
  );
  const line = (cells: readonly string[]): string =>
    `| ${cells.map((cell, column) => cell.padEnd(widths[column] ?? 0)).join(' | ')} |`;
  return [line(header), line(widths.map((width) => '-'.repeat(width))), ...rows.map(line)];
}
