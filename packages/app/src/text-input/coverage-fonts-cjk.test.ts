/// <reference types="node" />
// The CJK coverage families' slice faces (packages/app/scripts/build-cjk-slices.ts
// writes the files under assets/fonts/cjk) — for each face and weight, every slice of its cmap, in slice order. Fails
// when a face or the slicing changed and the list was not regenerated:
//
//   UPDATE_BUNDLED_METRICS=1 pnpm vitest run --project @canvas/app coverage-fonts-cjk
//   pnpm exec prettier --write packages/app/src/text-input/coverage-fonts-cjk.ts
import { readFileSync, writeFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import {
  cjkSliceFace,
  cjkSliceIdOf,
  cjkSlices,
  HAN_LANGUAGE_FAMILIES,
  parseFont,
} from '@canvas/text';

import { CJK_SLICE_FONT_FAMILIES } from './coverage-fonts-cjk.js';

const COVERAGE = new URL('../../assets/fonts/script-coverage/', import.meta.url);

/** A CJK face's slice ids and file stem: the folder (`notosanssc`) and weight. */
interface SlicedFace {
  readonly family: string;
  readonly weight: 400 | 700;
  readonly folder: string;
  readonly ids: readonly string[];
}

/**
 * Every CJK face's slices, from the coverage catalogue and the face files.
 *
 * @returns The faces, in catalogue order.
 */
function slicedFaces(): SlicedFace[] {
  const catalogue = JSON.parse(readFileSync(new URL('catalogue.json', COVERAGE), 'utf8')) as {
    entries: { family: string; faces: { weight: 400 | 700; url: string }[] }[];
  };
  return catalogue.entries
    .filter(({ family }) => HAN_LANGUAGE_FAMILIES.includes(family))
    .flatMap(({ family, faces }) =>
      faces.map(({ weight, url }) => {
        const codepoints = parseFont(readFileSync(new URL(url, COVERAGE)))
          .characterMap()
          .map(([codepoint]) => codepoint);
        return {
          family,
          weight,
          folder: url.slice(0, url.indexOf('/')).replace(/^notosans/u, ''),
          ids: [...cjkSlices(family, codepoints).keys()],
        };
      }),
    );
}

if (process.env.UPDATE_BUNDLED_METRICS === '1') {
  const faces = slicedFaces();
  const rows = faces.map(
    ({ family, folder, weight, ids }) =>
      `  ['${family}', '${folder}', ${String(weight)}, '${ids.join(',')}'],`,
  );
  writeFileSync(
    new URL('./cjk-slice-table.ts', import.meta.url),
    '// Generated by src/text-input/coverage-fonts-cjk.test.ts; do not edit.\n\n' +
      '/**\n * Each CJK coverage face\u2019s slices: family, folder, weight and its slice ids\n' +
      ' * (`cjkSlices` over its cmap), comma-separated, in slice order.\n */\n' +
      'export const CJK_SLICE_TABLE: readonly (readonly [\n' +
      '  family: string,\n  folder: string,\n  weight: 400 | 700,\n  ids: string,\n' +
      `])[] = [\n${rows.join('\n')}\n];\n`,
  );
  // Each family's slice files' URLs, one static `new URL(…?no-inline)` each: the library build
  // inlines every other asset, and a dynamic URL cannot carry the query.
  for (const folder of [...new Set(faces.map((face) => face.folder))]) {
    const urls = faces
      .filter((face) => face.folder === folder)
      .flatMap(({ weight, ids }) =>
        ids.map(
          (id) =>
            `  new URL('../../assets/fonts/cjk/${folder}/${String(weight)}-${id}.ttf?no-inline', import.meta.url).href,`,
        ),
      );
    writeFileSync(
      new URL(`./cjk-slice-urls-${folder}.ts`, import.meta.url),
      '// Generated by src/text-input/coverage-fonts-cjk.test.ts; do not edit.\n\n' +
        `/** The ${folder.toUpperCase()} slice files' URLs, in CJK_SLICE_TABLE order. */\n` +
        `export const CJK_SLICE_URLS_${folder.toUpperCase()}: readonly string[] = [\n${urls.join('\n')}\n];\n`,
    );
  }
}

describe('the CJK slice faces', () => {
  it('lists every slice of every CJK face and weight, in slice order', () => {
    const listed = CJK_SLICE_FONT_FAMILIES.flatMap(({ faces }) =>
      faces.map((face) => ({ family: face.family, weight: face.weight, id: cjkSliceIdOf(face) })),
    );
    expect(listed).toEqual(
      slicedFaces().flatMap(({ family, weight, ids }) => ids.map((id) => ({ family, weight, id }))),
    );
  });

  it('points each slice at its file under cjk', () => {
    for (const { faces } of CJK_SLICE_FONT_FAMILIES) {
      for (const face of faces) {
        expect(face).toMatchObject(cjkSliceFace(face, cjkSliceIdOf(face) ?? ''));
        expect(face.url).toMatch(
          new RegExp(`/cjk/[a-z]{2}/${String(face.weight)}-${cjkSliceIdOf(face) ?? ''}\\.ttf`),
        );
      }
    }
  });
});
