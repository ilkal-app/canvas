/// <reference types="node" />
// The file each bundled face's metrics were generated from, so agent-side measurement
// can shape with the same bytes the app draws with. The table in font-files.ts lists every face
// the generated metrics hold (the bundled families and the symbol coverage faces), by path from
// the repository root. Fails when a font or a catalogue changes and the table was not
// regenerated, which the metrics regeneration does too:
//
//   UPDATE_BUNDLED_METRICS=1 pnpm vitest run --project @canvas/text bundled-font-files
//   pnpm exec prettier --write packages/text/src/bundled/font-files.ts
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { fontFaceId, type FontFaceKey } from '../font/font-face.js';
import { SYMBOL_COVERAGE_FAMILIES } from '../symbols/symbol-coverage.js';

import { bundledFontFile, bundledFontFilePaths } from './bundled-font-file.js';
import { bundledFamilyMetrics, BUNDLED_FONT_FAMILIES } from './bundled-fonts.js';
import { symbolCoverageMetrics } from './coverage-fonts.js';
import { BUNDLED_FONT_FILES } from './font-files.js';

const REPO_ROOT = new URL('../../../../', import.meta.url);
const LIBRARY = 'packages/app/assets/fonts/library/';
const COVERAGE = 'packages/app/assets/fonts/script-coverage/';
const ENGINE_FONTS = 'packages/engine/assets/fonts/';

interface Catalogue {
  readonly entries: readonly {
    readonly family: string;
    readonly faces: readonly {
      weight: 400 | 700;
      isItalic: boolean;
      url: string;
      /** The file a measuring server shapes with, when not `url`. */
      metricsUrl?: string;
    }[];
  }[];
}

interface FaceFile extends FontFaceKey {
  readonly path: string;
}

/**
 * Reads a font catalogue.
 *
 * @param folder - The catalogue's folder, from the repository root.
 * @returns The catalogue.
 */
function catalogueOf(folder: string): Catalogue {
  return JSON.parse(
    readFileSync(new URL(`${folder}catalogue.json`, REPO_ROOT), 'utf8'),
  ) as Catalogue;
}

/**
 * Every bundled face's file, as the metrics generators read them: Liberation Sans from the
 * engine's fonts, the library from its catalogue, the symbol faces from the coverage catalogue.
 *
 * @returns The faces and their paths.
 */
function faceFiles(): FaceFile[] {
  const liberation = (weight: 400 | 700, isItalic: boolean, name: string): FaceFile => ({
    family: 'Liberation Sans',
    weight,
    isItalic,
    path: `${ENGINE_FONTS}LiberationSans-${name}.ttf`,
  });
  const coverage = catalogueOf(COVERAGE);
  return [
    liberation(400, false, 'Regular'),
    liberation(700, false, 'Bold'),
    liberation(400, true, 'Italic'),
    liberation(700, true, 'BoldItalic'),
    ...catalogueOf(LIBRARY).entries.flatMap(({ family, faces }) =>
      faces.map(({ weight, isItalic, url }) => ({
        family,
        weight,
        isItalic,
        path: `${LIBRARY}${url}`,
      })),
    ),
    ...SYMBOL_COVERAGE_FAMILIES.flatMap((family) =>
      (coverage.entries.find((entry) => entry.family === family)?.faces ?? []).map(
        ({ weight, isItalic, url, metricsUrl }) => ({
          family,
          weight,
          isItalic,
          path: `${COVERAGE}${metricsUrl ?? url}`,
        }),
      ),
    ),
  ];
}

if (process.env.UPDATE_BUNDLED_METRICS === '1') {
  const rows = faceFiles().map(
    ({ family, weight, isItalic, path }) =>
      `  [${JSON.stringify(family)}, ${String(weight)}, ${String(isItalic)}, ${JSON.stringify(path)}],`,
  );
  writeFileSync(
    new URL('./font-files.ts', import.meta.url),
    [
      '// Generated by src/bundled/bundled-font-files.test.ts; do not edit.',
      "import type { FontWeight } from '@canvas/schema';",
      '',
      '/**',
      ' * The file each bundled face (family and symbol coverage) was generated from:',
      ' * family, weight, italic, and the path from the repository root.',
      ' */',
      'export const BUNDLED_FONT_FILES: readonly (readonly [',
      '  family: string,',
      '  weight: FontWeight,',
      '  isItalic: boolean,',
      '  path: string,',
      '])[] = [',
      ...rows,
      '];',
      '',
    ].join('\n'),
  );
}

describe('bundled font files', () => {
  it('lists each file once, in table order, for a server to deploy', () => {
    const paths = bundledFontFilePaths();
    expect(new Set(paths).size).toBe(paths.length);
    expect(paths).toEqual([...new Set(BUNDLED_FONT_FILES.map(([, , , path]) => path))]);
  });

  it('lists the file of every face, as the catalogues name them', () => {
    expect(
      BUNDLED_FONT_FILES.map(([family, weight, isItalic, path]) => ({
        family,
        weight,
        isItalic,
        path,
      })),
    ).toEqual(faceFiles());
  });

  it('has a file on disk for every face the generated metrics hold, and only for those', () => {
    const faces = [
      ...BUNDLED_FONT_FAMILIES.flatMap((family) => bundledFamilyMetrics(family) ?? []),
      ...symbolCoverageMetrics(),
    ].map(({ face }) => face);
    for (const face of faces) {
      const path = bundledFontFile(face);
      expect(path, fontFaceId(face)).toBeDefined();
      expect(existsSync(new URL(path ?? '', REPO_ROOT)), path).toBe(true);
    }
    expect(BUNDLED_FONT_FILES).toHaveLength(faces.length);
  });
});
