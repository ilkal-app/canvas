/// <reference types="node" />
// The script table is generated from the Unicode Character Database 17.0.0 (the gzipped
// files under ../unicode/__fixtures__/ucd-17.0.0): each codepoint's Script (Scripts.txt, unlisted
// codepoints Zzzz) and Script_Extensions (ScriptExtensions.txt, unlisted codepoints just their
// Script), by ISO 15924 short name (PropertyValueAliases.txt). Regenerated with:
//
//   UPDATE_UNICODE_DATA=1 node_modules/.bin/vitest run --project @canvas/text script-table.test
//   node_modules/.bin/prettier --write packages/text/src/script/script-data.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';

import { describe, expect, it } from 'vitest';

import {
  SCRIPT_CODE_LIST,
  SCRIPT_EXTENSIONS,
  SCRIPT_RANGE_STARTS,
  SCRIPT_RANGE_VALUES,
} from './script-data.js';

const UCD = new URL('../unicode/__fixtures__/ucd-17.0.0/', import.meta.url);
const CODEPOINTS = 0x110000;

/**
 * A gzipped UCD file's lines, comments and blanks removed.
 *
 * @param name - The file's name, without `.gz`.
 * @returns Its data lines' fields, trimmed.
 */
function fieldsOf(name: string): string[][] {
  const text = gunzipSync(readFileSync(new URL(`${name}.gz`, UCD))).toString('utf8');
  return text
    .split('\n')
    .map((line) => line.replace(/#.*/u, '').trim())
    .filter((line) => line.length > 0)
    .map((line) => line.split(';').map((field) => field.trim()));
}

/**
 * The codepoints a `XXXX` or `XXXX..YYYY` field names.
 *
 * @param field - The field.
 * @returns Its first and last codepoints.
 */
function rangeOf(field: string): [first: number, last: number] {
  const [first = '', last = first] = field.split('..');
  return [Number.parseInt(first, 16), Number.parseInt(last, 16)];
}

/**
 * The generated data, as UCD 17.0.0 gives it.
 *
 * @returns The script codes, the Script ranges and the Script_Extensions entries.
 * @throws {Error} When a file names a script PropertyValueAliases does not.
 */
function generated(): {
  codes: string;
  starts: string;
  values: string;
  extensions: string;
} {
  const aliases = fieldsOf('PropertyValueAliases.txt').filter(([property]) => property === 'sc');
  const codes = aliases.map(([, short = '']) => short);
  const indexOfLong = new Map(aliases.map(([, , long = ''], index) => [long, index]));
  const indexOfShort = new Map(codes.map((code, index) => [code, index]));
  const scripts = new Uint8Array(CODEPOINTS).fill(indexOfShort.get('Zzzz') ?? 0);
  for (const [range = '', name = ''] of fieldsOf('Scripts.txt')) {
    const index = indexOfLong.get(name);
    if (index === undefined) throw new Error(`Unknown script ${name}`);
    const [first, last] = rangeOf(range);
    scripts.fill(index, first, last + 1);
  }
  const starts: string[] = [];
  const values: string[] = [];
  let previousStart = 0;
  for (let codepoint = 0; codepoint < CODEPOINTS; codepoint += 1) {
    if (codepoint > 0 && scripts[codepoint] === scripts[codepoint - 1]) continue;
    starts.push((codepoint - previousStart).toString(36));
    values.push((scripts[codepoint] ?? 0).toString(36));
    previousStart = codepoint;
  }
  const extensions = fieldsOf('ScriptExtensions.txt').map(([range = '', names = '']) => {
    const [first, last] = rangeOf(range);
    const indices = names.split(/\s+/u).map((code) => {
      const index = indexOfShort.get(code);
      if (index === undefined) throw new Error(`Unknown script ${code}`);
      return index.toString(36);
    });
    return `${first.toString(36)}-${last.toString(36)}:${indices.join(' ')}`;
  });
  return {
    codes: codes.join(','),
    starts: starts.join(','),
    values: values.join(','),
    extensions: extensions.join(','),
  };
}

if (process.env.UPDATE_UNICODE_DATA === '1') {
  const data = generated();
  writeFileSync(
    new URL('./script-data.ts', import.meta.url),
    [
      '// Generated by src/script/script-table.test.ts from UCD 17.0.0; do not edit.',
      '',
      '/** Every Script value, ISO 15924 short names, in PropertyValueAliases order. */',
      `export const SCRIPT_CODE_LIST = '${data.codes}';`,
      '',
      '/** Where each range of one Script starts: base-36 gaps from the previous start. */',
      `export const SCRIPT_RANGE_STARTS = '${data.starts}';`,
      '',
      "/** Each range's Script, a base-36 index into the code list. */",
      `export const SCRIPT_RANGE_VALUES = '${data.values}';`,
      '',
      '/** Script_Extensions: base-36 `first-last:index index…` entries, ascending. */',
      `export const SCRIPT_EXTENSIONS = '${data.extensions}';`,
      '',
    ].join('\n'),
  );
}

describe('the generated script table', () => {
  it('is what UCD 17.0.0 gives', () => {
    expect({
      codes: SCRIPT_CODE_LIST,
      starts: SCRIPT_RANGE_STARTS,
      values: SCRIPT_RANGE_VALUES,
      extensions: SCRIPT_EXTENSIONS,
    }).toEqual(generated());
  });
});
