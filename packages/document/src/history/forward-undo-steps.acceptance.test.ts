// A split command through a forwarding store belongs to the root store's undo group.
import { describe, expect, it } from 'vitest';

import { applyCommand, testEnvironment } from '../commands/__fixtures__/command-fixtures.js';
import { newRectangle } from '../commands/__fixtures__/component-boards.js';
import { createObjectsCommand } from '../commands/create-objects.js';
import type { NewObject } from '../commands/new-object-schema.js';
import { forwardUndoSteps } from '../index.js';
import { ADA } from '../store/__fixtures__/store-fixtures.js';
import type { DocumentStore } from '../store/document-store.js';
import { YjsDocumentStore } from '../store/yjs-document-store.js';
import { createLargeBoardObjects } from '../synthetic/large-board.js';

import { ADA_ID } from './__fixtures__/history-fixtures.js';
import { runAsOneStep } from './undo-groups.js';
import { createHistory } from './undo-manager.js';

/** Fields stamped by createObjects rather than supplied by a listed object. */
const GENERATED = new Set(['z', 'createdBy', 'createdAt', 'updatedAt']);

/**
 * Lists the deterministic large-board mix for createObjects.
 *
 * @param count - Number of objects.
 * @returns The objects without fields generated by the command.
 */
function listed(count: number): NewObject[] {
  return createLargeBoardObjects(count, 557).map(
    (object) =>
      Object.fromEntries(
        Object.entries(object).filter(([key]) => !GENERATED.has(key)),
      ) as unknown as NewObject,
  );
}

/**
 * Makes a distinct store identity whose methods delegate to the inner store.
 *
 * @param store - The store receiving every transaction.
 * @returns A forwarding DocumentStore.
 */
function wrapperOf(store: DocumentStore): DocumentStore {
  return new Proxy(store, {
    get(target, property) {
      const value: unknown = Reflect.get(target, property);
      if (typeof value !== 'function') return value;
      const callable = value as (...args: unknown[]) => unknown;
      return (...args: unknown[]): unknown => callable.apply(target, args);
    },
  });
}

describe('forwarded undo steps', { timeout: 30_000 }, () => {
  it.each([1, 2])('undoes and redoes a split create through %i registered wrapper(s)', (depth) => {
    const store = new YjsDocumentStore();
    applyCommand(store, createObjectsCommand, { objects: listed(10) }, ADA, testEnvironment(1));
    const before = new Set(store.read().objects.keys());
    const history = createHistory(store, ADA_ID, { captureTimeout: 0 });
    let writer: DocumentStore = store;
    for (let index = 0; index < depth; index += 1) {
      const wrapper = wrapperOf(writer);
      forwardUndoSteps(wrapper, writer);
      writer = wrapper;
    }

    applyCommand(writer, createObjectsCommand, { objects: listed(2_500) }, ADA, testEnvironment(2));
    const after = new Set(store.read().objects.keys());
    expect(store.read().objects.size).toBe(2_510);
    expect(history.undo()).toBe(true);
    expect(new Set(store.read().objects.keys())).toEqual(before);
    expect(history.canUndo()).toBe(false);
    expect(history.redo()).toBe(true);
    expect(new Set(store.read().objects.keys())).toEqual(after);
    expect(history.canRedo()).toBe(false);
    history.destroy();
    store.destroy();
  });

  it('joins a nested call through a wrapper to the open root group', () => {
    const store = new YjsDocumentStore();
    const wrapper = wrapperOf(store);
    forwardUndoSteps(wrapper, store);
    const history = createHistory(store, ADA_ID, { captureTimeout: 0 });
    const environment = testEnvironment(3);

    runAsOneStep(store, () => {
      applyCommand(
        store,
        createObjectsCommand,
        { objects: [newRectangle('outer', null, { x: 0, y: 0, width: 10, height: 10 })] },
        ADA,
        environment,
      );
      runAsOneStep(wrapper, () => {
        applyCommand(
          wrapper,
          createObjectsCommand,
          { objects: [newRectangle('inner', null, { x: 20, y: 0, width: 10, height: 10 })] },
          ADA,
          environment,
        );
      });
    });

    expect(store.read().objects.size).toBe(2);
    expect(history.undo()).toBe(true);
    expect(store.read().objects.size).toBe(0);
    expect(history.canUndo()).toBe(false);
    history.destroy();
    store.destroy();
  });
});
