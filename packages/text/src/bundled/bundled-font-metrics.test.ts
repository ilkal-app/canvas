/// <reference types="node" />
// The generated tables under generated/ against the font files they were made from: every face
// the app bundles (Liberation Sans in packages/engine/assets/fonts, the curated library listed by
// packages/app/assets/fonts/library/catalogue.json), decoded to exactly the metrics the app's
// font library builds from the file. Fails when a font or the catalogue changes and the tables
// were not regenerated:
//
//   UPDATE_BUNDLED_METRICS=1 pnpm vitest run --project @canvas/text bundled-font-metrics bundled-font-files expanding-codepoints
//   pnpm exec prettier --write packages/text/src/bundled/generated packages/text/src/bundled/font-files.ts packages/text/src/bundled/expanding-glyphs.ts
//
// (bundled-font-files regenerates the table of the faces' files, which agent-side shaping reads.)
import { readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import type { FontFaceKey } from '../font/font-face.js';
import { createFontMetrics, type FontMetrics } from '../font/font-metrics.js';
import { parseFont } from '../font/parse-font.js';

import {
  BUNDLED_FONT_FAMILIES,
  bundledFamilyMetrics,
  DEFAULT_FONT_FAMILY,
} from './bundled-fonts.js';
import type { FontCategory } from './encoded-family.js';
import { encodeFaceMetrics } from './face-encoding.js';
import { BUNDLED_FAMILIES } from './generated/index.js';

const ENGINE_FONTS = new URL('../../../engine/assets/fonts/', import.meta.url);
const LIBRARY = new URL('../../../app/assets/fonts/library/', import.meta.url);
const GENERATED = new URL('./generated/', import.meta.url);

interface FaceFile {
  readonly face: FontFaceKey;
  readonly file: URL;
}

interface CatalogueFace {
  readonly weight: 400 | 700;
  readonly isItalic: boolean;
  readonly url: string;
}

interface Catalogue {
  readonly entries: readonly {
    readonly family: string;
    readonly category: FontCategory;
    readonly faces: CatalogueFace[];
  }[];
}

/**
 * Every face the app bundles, the default family first and each family's faces in the order
 * listed.
 *
 * @returns The faces and their files.
 */
function bundledFaceFiles(): FaceFile[] {
  const liberation = (weight: 400 | 700, isItalic: boolean, name: string): FaceFile => ({
    face: { family: DEFAULT_FONT_FAMILY, weight, isItalic },
    file: new URL(`LiberationSans-${name}.ttf`, ENGINE_FONTS),
  });
  const catalogue = JSON.parse(
    readFileSync(new URL('catalogue.json', LIBRARY), 'utf8'),
  ) as Catalogue;
  return [
    liberation(400, false, 'Regular'),
    liberation(700, false, 'Bold'),
    liberation(400, true, 'Italic'),
    liberation(700, true, 'BoldItalic'),
    ...catalogue.entries.flatMap(({ family, faces }) =>
      faces.map(({ weight, isItalic, url }) => ({
        face: { family, weight, isItalic },
        file: new URL(url, LIBRARY),
      })),
    ),
  ];
}

/**
 * Each bundled family's picker category: the default family's is sans; the library's are the
 * catalogue's.
 *
 * @returns The categories by family.
 */
function bundledCategories(): ReadonlyMap<string, FontCategory> {
  const catalogue = JSON.parse(
    readFileSync(new URL('catalogue.json', LIBRARY), 'utf8'),
  ) as Catalogue;
  return new Map<string, FontCategory>([
    [DEFAULT_FONT_FAMILY, 'sans'],
    ...catalogue.entries.map(({ family, category }) => [family, category] as const),
  ]);
}

/**
 * The module name a family's table is generated into.
 *
 * @param family - The family.
 * @returns A lower-case, hyphenated name.
 */
function moduleNameOf(family: string): string {
  return family.toLowerCase().replace(/[^a-z0-9]+/g, '-');
}

/**
 * The metrics the app's font library builds for a face, and its encoded table.
 *
 * @param faceFile - The face and its file.
 * @returns Both.
 */
function measuredFace(faceFile: FaceFile): { metrics: FontMetrics; encoded: string } {
  const bytes = readFileSync(faceFile.file);
  const font = parseFont(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.length));
  const metrics = createFontMetrics(faceFile.face, font);
  return { metrics, encoded: encodeFaceMetrics(metrics, font.unitsPerEm) };
}

/**
 * Writes the generated modules from the font files (`UPDATE_BUNDLED_METRICS=1`).
 *
 * @param faces - Every bundled face.
 */
function writeGenerated(faces: readonly FaceFile[]): void {
  const categories = bundledCategories();
  for (const name of readdirSync(GENERATED)) rmSync(new URL(name, GENERATED));
  const families = [...new Set(faces.map(({ face }) => face.family))];
  const header = '// Generated by src/bundled/bundled-font-metrics.test.ts; do not edit.\n';
  for (const family of families) {
    const entries = faces
      .filter(({ face }) => face.family === family)
      .map((faceFile) => {
        const { weight, isItalic } = faceFile.face;
        const { encoded } = measuredFace(faceFile);
        return `{ weight: ${String(weight)}, isItalic: ${String(isItalic)}, metrics: '${encoded}' }`;
      });
    writeFileSync(
      new URL(`${moduleNameOf(family)}.ts`, GENERATED),
      `${header}import type { EncodedFamily } from '../encoded-family.js';\n\n` +
        `/** ${family}'s faces. */\nexport const FAMILY: EncodedFamily = ` +
        `{ family: ${JSON.stringify(family).replace(/"/g, "'")}, ` +
        `category: '${categories.get(family) ?? 'sans'}', faces: [${entries.join(', ')}] };\n`,
    );
  }
  const names = families.map((family) => ({ family, name: moduleNameOf(family) }));
  const constantOf = (name: string): string => name.toUpperCase().replace(/-/g, '_');
  writeFileSync(
    new URL('index.ts', GENERATED),
    `${header}import type { EncodedFamily } from '../encoded-family.js';\n\n` +
      [...names]
        .sort((first, second) => first.name.localeCompare(second.name))
        .map(({ name }) => `import { FAMILY as ${constantOf(name)} } from './${name}.js';\n`)
        .join('') +
      "\n/** Each bundled family's encoded metrics, the default family first. */\n" +
      'export const BUNDLED_FAMILIES: readonly EncodedFamily[] = [\n' +
      `${names.map(({ name }) => `  ${constantOf(name)},`).join('\n')}\n];\n`,
  );
}

const faces = bundledFaceFiles();
if (process.env.UPDATE_BUNDLED_METRICS === '1') writeGenerated(faces);

describe('the bundled font metrics tables', () => {
  it('list every bundled family, the default first', () => {
    expect(BUNDLED_FONT_FAMILIES).toEqual([...new Set(faces.map(({ face }) => face.family))]);
    expect(BUNDLED_FONT_FAMILIES[0]).toBe(DEFAULT_FONT_FAMILY);
  });

  it('carry each family’s picker category from the catalogue', () => {
    const categories = bundledCategories();
    expect(new Map(BUNDLED_FAMILIES.map(({ family, category }) => [family, category]))).toEqual(
      new Map(BUNDLED_FONT_FAMILIES.map((family) => [family, categories.get(family)])),
    );
  });

  it.each(BUNDLED_FONT_FAMILIES)('decode to exactly the metrics of %s from its files', (family) => {
    const expected = faces
      .filter(({ face }) => face.family === family)
      .map((faceFile) => measuredFace(faceFile).metrics);
    expect(bundledFamilyMetrics(family)).toEqual(expected);
  });
});
