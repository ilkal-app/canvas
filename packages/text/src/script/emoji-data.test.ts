/// <reference types="node" />
// The emoji properties the emoji-presentation step reads are generated from the Unicode
// Character Database 17.0.0 (emoji-data.txt, gzipped under ../unicode/__fixtures__/ucd-17.0.0),
// not the JavaScript engine's own Unicode data, so Node (MCP) and every browser agree. Regenerated
// with the first command (whose own check still sees the old table, so it fails once), then
// checked by running the test again without the variable:
//
//   UPDATE_UNICODE_DATA=1 node_modules/.bin/vitest run --project @canvas/text emoji-data.test
//   node_modules/.bin/prettier --write packages/text/src/script/emoji-data.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';

import { describe, expect, it } from 'vitest';

import { EMOJI_MODIFIER_BASE_RANGES, EMOJI_PRESENTATION_RANGES } from './emoji-data.js';

const UCD = new URL('../unicode/__fixtures__/ucd-17.0.0/', import.meta.url);

/**
 * One property's ranges in emoji-data.txt, merged where they touch, as base-36 `first-last`.
 *
 * @param property - The property's name.
 * @returns The ranges, comma-separated.
 */
function rangesOf(property: string): string {
  const text = gunzipSync(readFileSync(new URL('emoji-data.txt.gz', UCD))).toString('utf8');
  const ranges: [number, number][] = [];
  for (const line of text.split('\n')) {
    const [range = '', name = ''] = line
      .replace(/#.*/u, '')
      .split(';')
      .map((field) => field.trim());
    if (name !== property) continue;
    const [first = '', last = first] = range.split('..');
    ranges.push([Number.parseInt(first, 16), Number.parseInt(last, 16)]);
  }
  ranges.sort((a, b) => a[0] - b[0]);
  const merged: [number, number][] = [];
  for (const [first, last] of ranges) {
    const previous = merged.at(-1);
    if (previous !== undefined && first <= previous[1] + 1)
      previous[1] = Math.max(previous[1], last);
    else merged.push([first, last]);
  }
  return merged.map(([first, last]) => `${first.toString(36)}-${last.toString(36)}`).join(',');
}

if (process.env.UPDATE_UNICODE_DATA === '1') {
  writeFileSync(
    new URL('./emoji-data.ts', import.meta.url),
    [
      '// Generated by src/script/emoji-data.test.ts from UCD 17.0.0; do not edit.',
      '',
      '/** Emoji_Presentation=Yes: base-36 `first-last` ranges, ascending. */',
      `export const EMOJI_PRESENTATION_RANGES = '${rangesOf('Emoji_Presentation')}';`,
      '',
      '/** Emoji_Modifier_Base=Yes: base-36 `first-last` ranges, ascending. */',
      `export const EMOJI_MODIFIER_BASE_RANGES = '${rangesOf('Emoji_Modifier_Base')}';`,
      '',
    ].join('\n'),
  );
}

describe('the generated emoji data', () => {
  it('is what UCD 17.0.0 gives', () => {
    expect({
      presentation: EMOJI_PRESENTATION_RANGES,
      modifierBase: EMOJI_MODIFIER_BASE_RANGES,
    }).toEqual({
      presentation: rangesOf('Emoji_Presentation'),
      modifierBase: rangesOf('Emoji_Modifier_Base'),
    });
  });
});
